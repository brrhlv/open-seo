/**
 * Turn a candidates JSON file into idempotent D1 SQL that saves the keywords,
 * their metrics and their tags to one project (CLIENT-SBLV-196). Equivalent to
 * `save_keywords` with tagMode "append": it only adds rows, never deletes.
 * The script writes the SQL to a file and touches no database; apply it
 * yourself (local: `wrangler d1 execute DB --local --file <out>`; production:
 * the CF D1 query API, one statement per line).
 *
 * Input: { candidates: [{ keyword, usVolume?, keywordDifficulty?, cpc?,
 *   intent?, monthlySearches?: [{ year, month, searchVolume }], tags: string[] }] }
 *
 * Usage:
 *   pnpm exec tsx scripts/saved-keywords-seed-sql.ts \
 *     --input=keyword-ideas.json --projectId=<uuid> --out=seed.sql \
 *     [--location=2840] [--language=en] [--fetchedAt=2026-11-03T07:27:39.000Z]
 */

import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { parseArgs } from "./cli-utils";

const INTENTS = new Set([
  "informational",
  "commercial",
  "transactional",
  "navigational",
  "unknown",
]);

type Candidate = {
  keyword: string;
  usVolume?: number | null;
  keywordDifficulty?: number | null;
  cpc?: number | null;
  intent?: string | null;
  monthlySearches?: { year: number; month: number; searchVolume: number }[];
  tags?: string[];
};

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;

function n(value: unknown, { int = false, min = 0, max = Infinity } = {}) {
  if (typeof value !== "number" || !Number.isFinite(value)) return "NULL";
  if (value < min || value > max) return "NULL";
  return String(int ? Math.round(value) : value);
}

/** Same rules as normalizeKeyword / normalizeSavedKeywordTag in the app. */
const normalizeKeyword = (value: string) => value.trim().toLowerCase();
function normalizeTag(value: string) {
  const name = value.trim().replace(/\s+/g, " ");
  return name ? { name, normalized: name.toLocaleLowerCase() } : null;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const { input, projectId, out } = args;
  if (!input || !projectId || !out) {
    throw new Error("Required: --input=<json> --projectId=<uuid> --out=<sql>");
  }
  const location = Number(args.location ?? 2840);
  const language = args.language ?? "en";
  const fetchedAt = args.fetchedAt ?? new Date().toISOString();

  const doc = JSON.parse(readFileSync(input, "utf8")) as {
    candidates: Candidate[];
  };
  const lines: string[] = [
    `-- Saved keywords seed for project ${projectId} (${doc.candidates.length} candidates).`,
    "-- Idempotent: re-running adds nothing new. Generated by scripts/saved-keywords-seed-sql.ts.",
  ];

  const tags = new Map<string, string>();
  for (const c of doc.candidates) {
    for (const raw of c.tags ?? []) {
      const tag = normalizeTag(raw);
      if (tag && !tags.has(tag.normalized)) tags.set(tag.normalized, tag.name);
    }
  }
  for (const [normalized, name] of tags) {
    lines.push(
      `INSERT OR IGNORE INTO saved_keyword_tags (id, project_id, name, normalized_name) VALUES (${q(crypto.randomUUID())}, ${q(projectId)}, ${q(name)}, ${q(normalized)});`,
    );
  }

  const seen = new Set<string>();
  for (const c of doc.candidates) {
    const keyword = normalizeKeyword(c.keyword);
    if (!keyword || seen.has(keyword)) continue;
    seen.add(keyword);
    const key = `${q(projectId)}, ${q(keyword)}, ${location}, ${q(language)}`;
    const intent = c.intent && INTENTS.has(c.intent) ? q(c.intent) : "NULL";
    const monthly = JSON.stringify(
      (c.monthlySearches ?? []).map(({ year, month, searchVolume }) => ({
        year,
        month,
        searchVolume,
      })),
    );
    const metrics = [
      n(c.usVolume, { int: true }),
      n(c.cpc),
      n(c.keywordDifficulty, { int: true, max: 100 }),
      intent,
      q(monthly),
      q(fetchedAt),
    ];

    lines.push(
      `INSERT OR IGNORE INTO saved_keywords (id, project_id, keyword, location_code, language_code) VALUES (${q(crypto.randomUUID())}, ${key});`,
      `INSERT INTO keyword_metrics (project_id, keyword, location_code, language_code, search_volume, cpc, keyword_difficulty, intent, monthly_searches, fetched_at) VALUES (${key}, ${metrics.join(", ")}) ON CONFLICT (project_id, keyword, location_code, language_code) DO UPDATE SET search_volume = excluded.search_volume, cpc = excluded.cpc, keyword_difficulty = excluded.keyword_difficulty, intent = excluded.intent, monthly_searches = excluded.monthly_searches, fetched_at = excluded.fetched_at;`,
    );
    for (const raw of c.tags ?? []) {
      const tag = normalizeTag(raw);
      if (!tag) continue;
      lines.push(
        `INSERT OR IGNORE INTO saved_keyword_tag_assignments (saved_keyword_id, tag_id) SELECT k.id, t.id FROM saved_keywords k, saved_keyword_tags t WHERE k.project_id = ${q(projectId)} AND k.keyword = ${q(keyword)} AND k.location_code = ${location} AND k.language_code = ${q(language)} AND t.project_id = ${q(projectId)} AND t.normalized_name = ${q(tag.normalized)};`,
      );
    }
  }

  writeFileSync(out, `${lines.join("\n")}\n`);
  console.log(
    `Wrote ${lines.length - 2} statements (${seen.size} keywords, ${tags.size} tags) to ${out}`,
  );
}

main();
