import { normalizeKeyword } from "@/server/features/keywords/services/research/helpers";
import { normalizeSavedKeywordTag } from "@/shared/saved-keyword-tags";

// CLIENT-SBLV-196: idempotent D1 SQL that saves keywords, their metrics and
// their tags to one project, the same rows `save_keywords` (tagMode append)
// writes. Pure: scripts/saved-keywords-seed-sql.ts reads the file and writes
// the SQL; nothing here touches a database.

const INTENTS = new Set([
  "informational",
  "commercial",
  "transactional",
  "navigational",
  "unknown",
]);

export type SeedCandidate = {
  keyword: string;
  usVolume?: number | null;
  keywordDifficulty?: number | null;
  cpc?: number | null;
  intent?: string | null;
  monthlySearches?: { year: number; month: number; searchVolume: number }[];
  tags?: string[];
};

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;

function n(value: unknown, { int = false, max = Infinity } = {}) {
  if (typeof value !== "number" || !Number.isFinite(value)) return "NULL";
  if (value < 0 || value > max) return "NULL";
  return String(int ? Math.round(value) : value);
}

export function buildSavedKeywordsSeedSql(input: {
  candidates: SeedCandidate[];
  projectId: string;
  locationCode: number;
  languageCode: string;
  /** Stored as keyword_metrics.fetched_at; a re-run only updates older rows. */
  fetchedAt: string;
  newId?: () => string;
}) {
  const { candidates, projectId, locationCode, languageCode, fetchedAt } =
    input;
  const newId = input.newId ?? (() => crypto.randomUUID());
  const statements: string[] = [];

  const tags = new Map<string, string>();
  for (const c of candidates) {
    for (const raw of c.tags ?? []) {
      const tag = normalizeSavedKeywordTag(raw);
      if (tag && !tags.has(tag.normalizedName)) {
        tags.set(tag.normalizedName, tag.name);
      }
    }
  }
  for (const [normalized, name] of tags) {
    statements.push(
      `INSERT OR IGNORE INTO saved_keyword_tags (id, project_id, name, normalized_name) VALUES (${q(newId())}, ${q(projectId)}, ${q(name)}, ${q(normalized)});`,
    );
  }

  const seen = new Set<string>();
  for (const c of candidates) {
    const keyword = normalizeKeyword(c.keyword);
    if (!keyword || seen.has(keyword)) continue;
    seen.add(keyword);
    const key = `${q(projectId)}, ${q(keyword)}, ${locationCode}, ${q(languageCode)}`;
    const intent = c.intent && INTENTS.has(c.intent) ? q(c.intent) : "NULL";
    const monthly = JSON.stringify(
      (c.monthlySearches ?? []).map(({ year, month, searchVolume }) => ({
        year,
        month,
        searchVolume,
      })),
    );
    const metrics = [
      n(c.usVolume, { int: true }),
      n(c.cpc),
      n(c.keywordDifficulty, { int: true, max: 100 }),
      intent,
      q(monthly),
      q(fetchedAt),
    ];
    statements.push(
      `INSERT OR IGNORE INTO saved_keywords (id, project_id, keyword, location_code, language_code) VALUES (${q(newId())}, ${key});`,
      // Only replaces older metrics, so a re-run of an old seed never rolls
      // back a fresher refresh.
      `INSERT INTO keyword_metrics (project_id, keyword, location_code, language_code, search_volume, cpc, keyword_difficulty, intent, monthly_searches, fetched_at) VALUES (${key}, ${metrics.join(", ")}) ON CONFLICT (project_id, keyword, location_code, language_code) DO UPDATE SET search_volume = excluded.search_volume, cpc = excluded.cpc, keyword_difficulty = excluded.keyword_difficulty, intent = excluded.intent, monthly_searches = excluded.monthly_searches, fetched_at = excluded.fetched_at WHERE excluded.fetched_at > keyword_metrics.fetched_at;`,
    );
    for (const raw of c.tags ?? []) {
      const tag = normalizeSavedKeywordTag(raw);
      if (!tag) continue;
      statements.push(
        `INSERT OR IGNORE INTO saved_keyword_tag_assignments (saved_keyword_id, tag_id) SELECT k.id, t.id FROM saved_keywords k, saved_keyword_tags t WHERE k.project_id = ${q(projectId)} AND k.keyword = ${q(keyword)} AND k.location_code = ${locationCode} AND k.language_code = ${q(languageCode)} AND t.project_id = ${q(projectId)} AND t.normalized_name = ${q(tag.normalizedName)};`,
      );
    }
  }

  const header = [
    `-- Saved keywords seed for project ${projectId} (${candidates.length} candidates).`,
    "-- Idempotent: re-running adds nothing new and never overwrites newer metrics.",
    "-- Generated by scripts/saved-keywords-seed-sql.ts.",
  ];
  return {
    sql: `${[...header, ...statements].join("\n")}\n`,
    statementCount: statements.length,
    keywordCount: seen.size,
    tagCount: tags.size,
  };
}
